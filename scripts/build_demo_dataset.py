"""Generate the redistributable Corpus demo dataset (Workstream E1).

The demo images are *synthetic TEM phantoms*, not micrographs. That is a
deliberate choice:

- redistribution is unambiguous (CC0, generated by this repository),
- every particle has exact ground truth, so the expected results are
  verifiable rather than merely recorded,
- the set is regenerable byte-for-byte from a fixed seed, which is what makes
  it usable as a regression fixture.

Real micrographs remain the subject of the scientific validation in
Workstream F; they are not required to demo the workflow.

Usage::

    python scripts/build_demo_dataset.py            # write the dataset
    python scripts/build_demo_dataset.py --check     # verify it is unchanged
"""

