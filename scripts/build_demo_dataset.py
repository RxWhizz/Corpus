def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="Verify the committed dataset matches the generator; do not write.")
    args = parser.parse_args(argv)

    rows, differences = build(check_only=args.check)
    if args.check and differences:
        print(json.dumps({"ok": False, "differences": differences}, indent=2))
        return 1
    print(json.dumps({
        "ok": True,
        "mode": "check" if args.check else "write",
        "images": len(rows),
        "output": str(DEMO_DIR.relative_to(REPO_ROOT)),
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
