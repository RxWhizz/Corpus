SHELL_DELTA = 70
CORE_DELTA = 175


def ellipse_polygon(cx, cy, ax, ay, angle_deg=0.0, points=32):
    """Closed polygon approximating an ellipse, as flat COCO coordinates."""
    angle = math.radians(angle_deg)
    cos_a, sin_a = math.cos(angle), math.sin(angle)
    coords = []
    for index in range(points):
        theta = 2 * math.pi * index / points
        x = ax * math.cos(theta)
        y = ay * math.sin(theta)
        coords.extend([round(cx + x * cos_a - y * sin_a, 2), round(cy + x * sin_a + y * cos_a, 2)])
    return coords


def _disc_mask(shape, center, radius):
    """Boolean mask of a filled disc."""
    mask = np.zeros(shape, dtype=np.uint8)
    cv2.circle(mask, center, radius, 255, -1)
    return mask > 0


def _ellipse_mask(shape, center, axes, angle):
    """Boolean mask of a filled, rotated ellipse."""
    mask = np.zeros(shape, dtype=np.uint8)
    cv2.ellipse(mask, center, axes, angle, 0, 360, 255, -1)
    return mask > 0


def render(spec):
    """Render one demo image and return ``(image, ground_truth_records)``."""
    rng = np.random.default_rng(spec["seed"])
    size = IMAGE_SIZE
    canvas = np.full((size, size), float(spec["background"]), dtype=np.float32)
    shell_delta = spec.get("shell_delta", SHELL_DELTA)
    core_delta = spec.get("core_delta", CORE_DELTA)
    truth = []

    for index, particle in enumerate(spec["particles"], start=1):
        cx, cy = particle["center"]
        kind = particle["kind"]

        if kind == "core_shell":
            outer_r, core_r = particle["outer_r"], particle["core_r"]
            outer = _disc_mask(canvas.shape, (cx, cy), outer_r)
            core = _disc_mask(canvas.shape, (cx, cy), core_r)
            canvas[outer & ~core] -= shell_delta
            canvas[core] -= core_delta
            truth.append({
                "particle_id": f"p{index:02d}", "kind": kind, "center": [cx, cy],
                "core_diameter_px": 2 * core_r, "outer_diameter_px": 2 * outer_r,
                "shell_thickness_px": outer_r - core_r,
                "polygons": {"Au_core": ellipse_polygon(cx, cy, core_r, core_r),
                             "SiO2_outer": ellipse_polygon(cx, cy, outer_r, outer_r)},
            })

        elif kind == "disc":
            radius = particle["r"]
            canvas[_disc_mask(canvas.shape, (cx, cy), radius)] -= core_delta
            truth.append({
                "particle_id": f"p{index:02d}", "kind": kind, "center": [cx, cy],
                "core_diameter_px": 2 * radius, "outer_diameter_px": 2 * radius,
                "shell_thickness_px": 0,
                "polygons": {"Au_core": ellipse_polygon(cx, cy, radius, radius)},
            })

        elif kind == "rod":
            ax, ay = particle["axes"]
            angle = particle["angle"]
            canvas[_ellipse_mask(canvas.shape, (cx, cy), (ax, ay), angle)] -= core_delta
            truth.append({
                "particle_id": f"p{index:02d}", "kind": kind, "center": [cx, cy],
                "major_axis_px": 2 * ax, "minor_axis_px": 2 * ay, "angle_deg": angle,
                "core_diameter_px": 2 * ax, "outer_diameter_px": 2 * ax, "shell_thickness_px": 0,
                "polygons": {"Au_core": ellipse_polygon(cx, cy, ax, ay, angle)},
            })

        elif kind == "decorated":
            carrier_r = particle["carrier_r"]
            decoration_r = particle["decoration_r"]
            count = particle["decorations"]
            canvas[_disc_mask(canvas.shape, (cx, cy), carrier_r)] -= shell_delta
            decorations = []
            for step in range(count):
                theta = 2 * math.pi * step / count
                dx = int(round(cx + 0.62 * carrier_r * math.cos(theta)))
                dy = int(round(cy + 0.62 * carrier_r * math.sin(theta)))
                canvas[_disc_mask(canvas.shape, (dx, dy), decoration_r)] -= core_delta
                decorations.append({"center": [dx, dy], "diameter_px": 2 * decoration_r})
            truth.append({
                "particle_id": f"p{index:02d}", "kind": kind, "center": [cx, cy],
                "outer_diameter_px": 2 * carrier_r, "core_diameter_px": 0,
                "shell_thickness_px": 0,
                "decoration_count": count, "decoration_diameter_px": 2 * decoration_r,
                "decorations": decorations,
                "polygons": {"SiO2_outer": ellipse_polygon(cx, cy, carrier_r, carrier_r)},
            })
        else:
            raise ValueError(f"Unknown particle kind: {kind}")

    # Mild illumination gradient and blur, so the image is not trivially clean.
    yy, xx = np.mgrid[0:size, 0:size]
    canvas += 6 * ((xx - size / 2) / size) + 4 * ((yy - size / 2) / size)
    smooth = cv2.GaussianBlur(canvas, (0, 0), sigmaX=1.1)
    canvas = smooth + rng.normal(0, spec["noise_std"], smooth.shape)
    canvas = np.clip(canvas, 0, 255).astype(np.uint8)

    # Printed scale bar of exactly SCALE_BAR["width_px"] pixels, placed low and
    # right, clear of every particle.
    bar_x = size - SCALE_BAR["margin"] - SCALE_BAR["width_px"]
    bar_y = size - SCALE_BAR["margin"]
    pad = SCALE_BAR["quiet_pad"]
    y0 = max(0, bar_y - pad)
    y1 = min(size, bar_y + SCALE_BAR["height_px"] + pad)
    x0 = max(0, bar_x - pad)
    x1 = min(size, bar_x + SCALE_BAR["width_px"] + pad)
    canvas[y0:y1, x0:x1] = np.clip(smooth[y0:y1, x0:x1], 0, 255).astype(np.uint8)

    # Inclusive end coordinates: the bounding box is exactly width_px x height_px.
    cv2.rectangle(
        canvas,
        (bar_x, bar_y),
        (bar_x + SCALE_BAR["width_px"] - 1, bar_y + SCALE_BAR["height_px"] - 1),
        255, -1,
    )

    return canvas, truth, {"x": bar_x, "y": bar_y, **SCALE_BAR}


def build(check_only=False):
    images_dir = DEMO_DIR / "images"
    annotations_dir = DEMO_DIR / "annotations"
    images_dir.mkdir(parents=True, exist_ok=True)
    annotations_dir.mkdir(parents=True, exist_ok=True)

    metadata_rows = []
    coco = {
        "info": {
            "description": "Corpus synthetic demo dataset with ground-truth masks",
            "license": LICENSE,
            "generator": "scripts/build_demo_dataset.py",
        },
        "licenses": [{"id": 1, "name": LICENSE, "url": "https://creativecommons.org/publicdomain/zero/1.0/"}],
        "images": [],
        "annotations": [],
        "categories": [
            {"id": 0, "name": "Au_core", "supercategory": "nanoparticle"},
            {"id": 1, "name": "SiO2_outer", "supercategory": "nanoparticle"},
        ],
    }
    category_ids = {"Au_core": 0, "SiO2_outer": 1}
    ground_truth = {}
    annotation_id = 1
    differences = []

    for image_index, spec in enumerate(SPECS, start=1):
        image, truth, bar = render(spec)
        scale_px = float(bar["width_px"])
        nm_per_px = spec["scale_nm"] / scale_px
        file_name = f"{spec['image_id']}.png"
        target = images_dir / file_name

        encoded = cv2.imencode(".png", image)[1].tobytes()
        if check_only:
            if not target.exists():
                differences.append(f"missing image: {file_name}")
            else:
                # Compare decoded pixels rather than encoded bytes: PNG encoder
                # output varies between OpenCV builds while the image content
                # is identical, and it is the content that matters here.
                committed = cv2.imread(str(target), cv2.IMREAD_UNCHANGED)
                if committed is None:
                    differences.append(f"could not decode committed image: {file_name}")
                elif committed.shape != image.shape or not np.array_equal(committed, image):
                    differences.append(f"image differs from the generator output: {file_name}")
        else:
            target.write_bytes(encoded)

        digest = hashlib.sha256(target.read_bytes() if target.exists() else encoded).hexdigest()
        metadata_rows.append({
            "image_id": spec["image_id"],
            "source_id": "corpus_synthetic_demo",
            "file_path": f"images/{file_name}",
            "file_sha256": digest,
            "width": IMAGE_SIZE,
            "height": IMAGE_SIZE,
            "modality": "synthetic_TEM_phantom",
            "morphology": spec["morphology"],
            "contrast": spec["contrast"],
            "particles": len(spec["particles"]),
            "scale_nm": spec["scale_nm"],
            "scale_px": scale_px,
            "nm_per_px": f"{nm_per_px:.10g}",
            "scale_status": "confirmed",
            "scale_bar_x": bar["x"],
            "scale_bar_y": bar["y"],
            "license": LICENSE,
            "license_status": "accepted",
            "redistribution": "allowed",
            "provenance": PROVENANCE,
            "source_url": "https://github.com/RxWhizz/Corpus",
            "quality_status": "ready",
            "curation_status": "ready",
            "metadata_status": "ready",
            "split": "demo",
            "seed": spec["seed"],
            "notes": "Synthetic phantom with exact ground truth; not a real micrograph.",
        })

        coco["images"].append({
            "id": image_index,
            "file_name": f"images/{file_name}",
            "width": IMAGE_SIZE,
            "height": IMAGE_SIZE,
            "license": 1,
            "source_id": "corpus_synthetic_demo",
            "nm_per_px": nm_per_px,
            "metadata": {
                "source_id": "corpus_synthetic_demo",
                "dataset_layer": "public_demo",
                "nm_per_px": nm_per_px,
                "license": LICENSE,
                "license_status": "accepted",
            },
        })

        for record in truth:
            for class_name, polygon in record["polygons"].items():
                xs = polygon[0::2]
                ys = polygon[1::2]
                coco["annotations"].append({
                    "id": annotation_id,
                    "image_id": image_index,
                    "category_id": category_ids[class_name],
                    "segmentation": [polygon],
                    "bbox": [min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)],
                    "area": round(cv2.contourArea(
                        np.array(polygon, dtype=np.float32).reshape(-1, 1, 2)), 2),
                    "iscrowd": 0,
                    "review_status": "ready",
                })
                annotation_id += 1

        ground_truth[spec["image_id"]] = {
            "nm_per_px": nm_per_px,
            "scale_nm": spec["scale_nm"],
            "scale_px": scale_px,
            "morphology": spec["morphology"],
            "particles": [
                {
                    **{key: value for key, value in record.items() if key != "polygons"},
                    "core_diameter_nm": record.get("core_diameter_px", 0) * nm_per_px,
                    "outer_diameter_nm": record.get("outer_diameter_px", 0) * nm_per_px,
                    "shell_thickness_nm": record.get("shell_thickness_px", 0) * nm_per_px,
                }
                for record in truth
            ],
        }

    artifacts = {
        DEMO_DIR / "metadata.csv": _csv_text(metadata_rows),
        annotations_dir / "demo_ground_truth_coco.json": json.dumps(coco, indent=2, sort_keys=True) + "\n",
        DEMO_DIR / "ground_truth.json": json.dumps(ground_truth, indent=2, sort_keys=True) + "\n",
        DEMO_DIR / "README.md": _readme(metadata_rows),
    }
    for path, text in artifacts.items():
        if check_only:
            if not path.exists():
                differences.append(f"missing: {path.relative_to(REPO_ROOT)}")
            elif path.read_text(encoding="utf-8") != text:
                differences.append(f"differs from the generator output: {path.relative_to(REPO_ROOT)}")
        else:
            path.write_text(text, encoding="utf-8")

    return metadata_rows, differences


def _csv_text(rows):
    import io

    buffer = io.StringIO(newline="")
    writer = csv.DictWriter(buffer, fieldnames=list(rows[0]), lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue()


